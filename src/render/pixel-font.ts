export interface BuiltinPixelFontData {
  spec: BitmapFontSpec;
  rgba: Uint8Array;
}

export function createBuiltinPixelFont(): BuiltinPixelFontData {
  const rgba = new Uint8Array(BUILTIN_FONT_WIDTH * BUILTIN_FONT_HEIGHT * 4);
  const glyphs: Record<number, BitmapFontGlyph> = {};

  const cols = 16;
  const cellW = 8;
  const cellH = 8;

  for (let code = 32; code <= 126; code++) {
    const ch = String.fromCharCode(code);
    const upper = ch.toUpperCase();
    const pattern = GLYPH_5X7[ch] ?? GLYPH_5X7[upper] ?? GLYPH_5X7[' '];

    const index = code - 32;
    const gx = (index % cols) * cellW;
    const gy = Math.floor(index / cols) * cellH;

    if (pattern) {
      for (let row = 0; row < 7; row++) {
        const bits = pattern[row] ?? 0;
        for (let col = 0; col < 5; col++) {
          if ((bits & (1 << (4 - col))) !== 0) {
            const px = gx + col;
            const py = gy + row;
            const off = (py * BUILTIN_FONT_WIDTH + px) * 4;
            rgba[off] = 255;
            rgba[off + 1] = 255;
            rgba[off + 2] = 255;
            rgba[off + 3] = 255;
          }
        }
      }
    }

    glyphs[code] = {
      id: code,
      x: gx,
      y: gy,
      width: 5,
      height: 7,
      xoffset: 0,
      yoffset: 0,
      xadvance: 6,
    };
  }

  return {
    rgba,
    spec: {
      name: '__builtin_pixel_font__',
      face: 'Pixel5x7',
      size: 7,
      lineHeight: 9,
      base: 7,
      scaleW: BUILTIN_FONT_WIDTH,
      scaleH: BUILTIN_FONT_HEIGHT,
      pageFile: '__builtin_pixel_font__',
      glyphs,
    },
  };
}

function resolveGlyph(font: BitmapFontSpec, charCode: number): BitmapFontGlyph | undefined {
  const direct = font.glyphs[charCode];
  if (direct) return direct;
  const ch = String.fromCharCode(charCode);
  const upperCode = ch.toUpperCase().charCodeAt(0);
  if (font.glyphs[upperCode]) return font.glyphs[upperCode];
  const lowerCode = ch.toLowerCase().charCodeAt(0);
  if (font.glyphs[lowerCode]) return font.glyphs[lowerCode];
  return font.glyphs[63] ?? font.glyphs[32]; // '?' or space
}

export function measureBitmapText(
  font: BitmapFontSpec,
  text: string,
  scale = 1,
): { width: number; height: number } {
  let width = 0;
  for (let i = 0; i < text.length; i++) {
    const glyph = resolveGlyph(font, text.charCodeAt(i));
    if (glyph) {
      width += glyph.xadvance * scale;
    } else {
      width += 6 * scale;
    }
  }
  return {
    width,
    height: font.lineHeight * scale,
  };
}

export type TextAlign = 'left' | 'center' | 'right';

export function buildBitmapTextVertices(
  font: BitmapFontSpec,
  text: string,
  x: number,
  y: number,
  scale = 1,
  align: TextAlign = 'left',
): Float32Array {
  if (text.length === 0) {
    return new Float32Array(0);
  }

  const metrics = measureBitmapText(font, text, scale);
  let cursorX = x;
  if (align === 'center') {
    cursorX = Math.round(x - metrics.width * 0.5);
  } else if (align === 'right') {
    cursorX = Math.round(x - metrics.width);
  } else {
    cursorX = Math.round(x);
  }
  const baseY = Math.round(y);

  // 6 vertices per glyph * 4 floats (px, py, u, v)
  const out = new Float32Array(text.length * 24);
  let writeIdx = 0;

  const invW = 1 / Math.max(1, font.scaleW);
  const invH = 1 / Math.max(1, font.scaleH);

  for (let i = 0; i < text.length; i++) {
    const glyph = resolveGlyph(font, text.charCodeAt(i));
    if (!glyph) {
      cursorX += 6 * scale;
      continue;
    }

    if (glyph.width > 0 && glyph.height > 0) {
      const x0 = cursorX + glyph.xoffset * scale;
      const y0 = baseY + glyph.yoffset * scale;
      const x1 = x0 + glyph.width * scale;
      const y1 = y0 + glyph.height * scale;

      const u0 = glyph.x * invW;
      const v0 = glyph.y * invH;
      const u1 = (glyph.x + glyph.width) * invW;
      const v1 = (glyph.y + glyph.height) * invH;

      // Triangle 1
      out[writeIdx++] = x0;
      out[writeIdx++] = y0;
      out[writeIdx++] = u0;
      out[writeIdx++] = v0;

      out[writeIdx++] = x1;
      out[writeIdx++] = y0;
      out[writeIdx++] = u1;
      out[writeIdx++] = v0;

      out[writeIdx++] = x0;
      out[writeIdx++] = y1;
      out[writeIdx++] = u0;
      out[writeIdx++] = v1;

      // Triangle 2
      out[writeIdx++] = x1;
      out[writeIdx++] = y0;
      out[writeIdx++] = u1;
      out[writeIdx++] = v0;

      out[writeIdx++] = x1;
      out[writeIdx++] = y1;
      out[writeIdx++] = u1;
      out[writeIdx++] = v1;

      out[writeIdx++] = x0;
      out[writeIdx++] = y1;
      out[writeIdx++] = u0;
      out[writeIdx++] = v1;
    }

    cursorX += glyph.xadvance * scale;
  }

  return writeIdx === out.length ? out : out.subarray(0, writeIdx);
}
